--  هذا الملف يضيف دعم حتى 20 صورة لكل مشروع بدل صورة واحدة.
--  يحافظ على الصورة الحالية لكل مشروع (image) وينقلها تلقائياً
--  لتكون أول صورة في القائمة الجديدة (images)، بدون ما يفقد أي بيانات.
--
--  شغّله من: Supabase → SQL Editor → New query → الصق هذا → Run
-- =========================================================

-- 1) إضافة عمود جديد images من نوع jsonb (مصفوفة روابط صور)
alter table projects
  add column if not exists images jsonb not null default '[]'::jsonb;

-- 2) نقل الصورة الحالية (إن وجدت) لتكون أول عنصر في العمود الجديد
update projects
set images = jsonb_build_array(image)
where image is not null and image <> '' and jsonb_array_length(images) = 0;

-- ملاحظة: عمود "image" القديم يبقى موجوداً بدون حذف، حفاظاً على التوافق
-- مع أي نسخة قديمة من الكود قد تحتاجه لاحقاً. الكود الجديد يعتمد على "images".
